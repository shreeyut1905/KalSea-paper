#!/usr/bin/env python3
"""Write the figure captions (figures/<fig>_caption.tex) with every number taken from the data files.

Each caption file holds \\caption{...}\\label{...}; use it inside the float, e.g.
    \\begin{figure*}[t]\\centering\\includegraphics[width=\\textwidth]{figures/fig_tradeoff.pdf}
    \\input{figures/fig_tradeoff_caption}\\end{figure*}
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.dirname(HERE)
ST = json.load(open(os.path.join(HERE, "data", "flux_drawbench_stats.json")))


def sg(v, nd=2):
    s = f"{v:+.{nd}f}"
    if float(s) == 0.0 and v != 0.0:      # e.g. -0.005 would print as -0.00: show one more digit
        s = f"{v:+.{nd + 1}f}"
    return s.replace("-", "$-$") if v < 0 else s


def ci(p, nd=2):
    return f"{sg(p['mean'], nd)}\\,dB [{sg(p['ci95'][0], nd)}, {sg(p['ci95'][1], nd)}]"


def nfe_label(x):
    return f"{x:.0f}" if abs(x - round(x)) < 0.05 else f"{x:.1f}"


def write(name, body, usage):
    path = os.path.join(FIG, f"{name}_caption.tex")
    open(path, "w").write(f"% Auto-generated by figures/src/make_captions.py (numbers from figures/src/data). Usage:\n% {usage}\n"
                          + body + "\n")
    print("wrote", path)


def tradeoff(long=False):
    P, S = ST["paired"], ST["summary"]
    lo_d = min(ST["deltas"], key=lambda d: S[d]["ours"]["nfe"])
    hi_d = max(ST["deltas"], key=lambda d: S[d]["ours"]["nfe"])
    sig_sea = [d for d in ST["deltas"] if P[d]["ours-seacache"]["psnr"]["ci95"][0] <= 0]
    lp = P[lo_d]["ours-seacache"]["lpips"]
    deltas = ", ".join(ST["deltas"])
    if not long:   # compact main-paper caption (8-page limit); same numbers
        body = (
            r"\caption{\textbf{Fidelity vs.\ compute on \flux} (DrawBench, 200 held-out prompts)."
            r" \textbf{(a)}~PSNR and \textbf{(b)}~LPIPS w.r.t.\ the 50-step reference vs.\ the mean number of transformer"
            rf" evaluations per image; the \sea-gate threshold $\delta \in \{{{deltas}\}}$, shared by all methods, sets the"
            r" budget, and gray bands mark the budgets of \cref{tab:flux-main}. All methods share code, seeds and hardware"
            r" (\seacache: our re-run of its released gate with reuse). Lines: means over prompts; shaded: 95\%"
            r" bootstrap CIs. \textbf{(c)}~Paired PSNR gain of \ours (95\% CIs): over \seacache, it grows from "
            + ci(P[lo_d]["ours-seacache"]["psnr"]) + rf" at {nfe_label(S[lo_d]['ours']['nfe'])} \nfe"
            + (r" (not significant)" if lo_d in sig_sea else "") + " to "
            + ci(P[hi_d]["ours-seacache"]["psnr"]) + rf" at {nfe_label(S[hi_d]['ours']['nfe'])} \nfe.}}" "\n"
            r"\label{fig:tradeoff}")
        write("fig_tradeoff", body, r"\begin{figure*}[t]\centering\includegraphics[width=\textwidth]{figures/fig_tradeoff.pdf}"
              r"\input{figures/fig_tradeoff_caption}\end{figure*}   (one-column variant: figures/fig_tradeoff_1col.pdf,"
              r" width=\columnwidth, same caption)")
        return
    body = (
        r"\caption{\textbf{Quality--compute trade-off on \flux} (DrawBench, 200 held-out prompts)."
        r" \textbf{(a)}~PSNR and \textbf{(b)}~LPIPS with respect to the 50-step reference vs.\ the mean number of transformer"
        rf" evaluations per image (\nfe). The budget is set by the \sea-gate threshold $\delta \in \{{{deltas}\}}$, shared by"
        r" all methods; gray bands mark the two budgets of \cref{tab:flux-main} ($\delta = 0.37$, $0.6$). Lines: means over"
        r" prompts; shaded: 95\% bootstrap CIs. \textbf{(c)}~Paired per-prompt PSNR gain of \ours over \seacache"
        r" (mean, 95\% bootstrap CI). The gain over \seacache grows with the budget, from "
        + ci(P[lo_d]["ours-seacache"]["psnr"]) + rf" at {nfe_label(S[lo_d]['ours']['nfe'])} \nfe"
        + (r" (not significant; LPIPS still improves by" if lo_d in sig_sea else r" (LPIPS improves by")
        + rf" {abs(lp['mean']):.3f} [{abs(lp['ci95'][1]):.3f}, {abs(lp['ci95'][0]):.3f}]) to "
        + ci(P[hi_d]["ours-seacache"]["psnr"]) + rf" at {nfe_label(S[hi_d]['ours']['nfe'])} \nfe. \seacache: \sea gate with residual reuse; \ours: \sea gate with"
        r" Kalman residual forecasting and predictor-corrector gap smoothing.}" "\n"
        r"\label{fig:tradeoff}")
    write("fig_tradeoff", body, r"\begin{figure*}[t]\centering\includegraphics[width=\textwidth]{figures/fig_tradeoff.pdf}"
          r"\input{figures/fig_tradeoff_caption}\end{figure*}   (one-column variant: figures/fig_tradeoff_1col.pdf,"
          r" width=\columnwidth, same caption)")


def teaser(tag, name, label):
    """Compact Fig.-1 caption (one row: median-gain prompt left, upper-quartile prompt right)."""
    meta = json.load(open(os.path.join(HERE, "qual_tiles", tag, "meta.json")))
    r = meta["rule"]
    gq = r["gain_quantiles"]
    assert [float(q) for q in r["quantiles"]] == [50.0, 75.0] and r["k"] == 1, r
    nfes = sorted({int(p["nfe"]) for p in meta["prompts"]})
    assert len(nfes) == 1, nfes
    ww, wh = r["window"]
    ratio = 50.0 / meta["nfe"]
    body = (
        rf"\caption{{\textbf{{Closing the loop at {nfes[0]} \nfe}} (\flux, $\delta = {meta['delta']}$, ${ratio:.1f}\times$"
        r" fewer transformer evaluations than the 50-step reference). \seacache (our run of its released gate) reuses the"
        r" last computed residual on skipped steps; \ours forecasts it with a Kalman filter and corrects each skipped gap"
        r" once the next step is computed (\pcgs). Fixed selection rule: among the "
        rf"{r['n_identical_steps']} of {r['n_total']} held-out DrawBench prompts on which the two caches computed the"
        r" same steps, those whose PSNR gain of \ours over \seacache is closest to the median"
        rf" ({sg(gq['50'])}\,dB; left) and the upper quartile ({sg(gq['75'])}\,dB; right). Crops (${ww}\times{wh}$"
        r" of $1024^2$ pixels) are placed where the cached images differ most, without using the reference. Numbers: PSNR"
        r" (dB) to the reference, best in bold.}" "\n" + rf"\label{{{label}}}")
    write(name, body, r"main.tex: inside \twocolumn[...] after \maketitle, \captionsetup{type=figure} +"
          rf" \includegraphics[width=\textwidth]{{figures/{name}.pdf}} + \input{{figures/{name}_caption}}")


def qualitative(tag, name, label, main=True, positions=None):
    meta = json.load(open(os.path.join(HERE, "qual_tiles", tag, "meta.json")))
    r = meta["rule"]
    gq = r["gain_quantiles"]
    nfes = sorted({int(p["nfe"]) for p in meta["prompts"]})
    nfe_txt = str(nfes[0]) if len(nfes) == 1 else f"{nfes[0]}--{nfes[-1]}"
    mean_nfe = meta["nfe"]
    qs = r["quantiles"]
    qn = {25.0: "lower quartile", 50.0: "median", 75.0: "upper quartile"}
    pos = positions or (["top row", "bottom row"] if len(qs) == 2 else ["top row", "middle row", "bottom row"])
    kk = {1: "the prompt", 2: "the two prompts", 3: "the three prompts"}.get(r["k"], f"the {r['k']} prompts")
    kk2 = {1: "the one", 2: "the two", 3: "the three"}.get(r["k"], f"the {r['k']}")
    parts = [(f"{kk} whose gain is closest to" if i == 0 else f"{kk2} closest to")
             + f" the {qn[q]} ({sg(gq[str(int(q))])}\\,dB; {pos[i]})" for i, q in enumerate(qs)]
    rows_txt = (" and ".join(parts) if len(parts) == 2 else f"{parts[0]}, {parts[1]} and {parts[2]}")
    ww, wh = r["window"]
    budget = (rf"{nfe_txt} \nfe" if len(nfes) == 1 else rf"{nfe_txt} \nfe (mean {mean_nfe:.1f})")
    ratio = 50.0 / mean_nfe
    body = (
        rf"\caption{{\textbf{{Qualitative comparison at {budget}}} (\flux, DrawBench, $\delta = {meta['delta']}$,"
        rf" ${ratio:.1f}\times$ fewer transformer evaluations than the 50-step reference)."
        r" The prompts are selected by a fixed rule, not by hand: among the "
        rf"{r['n_identical_steps']} of {r['n_total']} prompts on which \seacache and \ours computed the identical"
        r" set of steps, we compute the per-prompt PSNR gain of \ours over \seacache and show "
        rf"{rows_txt}."
        rf" Below each image, a fixed ${ww}\times{wh}$-pixel crop (of $1024\times1024$) is magnified; it is placed where"
        r" the two accelerated samples differ most (largest mean absolute difference), without"
        r" looking at the reference. Numbers: PSNR (dB) with respect to the reference, best in bold."
        + (r" Examples near the lower quartile and at the $\approx$21-\nfe budget are in the supplementary material."
           if main else "")
        + "}\n" + rf"\label{{{label}}}")
    write(name, body, rf"\begin{{figure*}}[t]\centering\includegraphics[width=\textwidth]{{figures/{name}.pdf}}"
          rf"\input{{figures/{name}_caption}}\end{{figure*}}")


VNAME = {"hunyuan": "HunyuanVideo", "wan": "Wan2.1-1.3B"}
VGATE = {"hunyuan": ", gate on the sampler's noise level", "wan": ""}


def qual_models(flux_tag="nfe13_teaser"):
    """main paper: one upper-quartile example per model (fig_qual_models.py)"""
    fm = json.load(open(os.path.join(HERE, "qual_tiles", flux_tag, "meta.json")))
    V = {m: json.load(open(os.path.join(HERE, "qual_tiles", f"video_{m}", "meta.json"))) for m in ("hunyuan", "wan")}
    fq = next(p for p in fm["prompts"] if float(p["quantile"]) == 75.0)
    vq = {m: next(p for p in V[m]["prompts"] if float(p["quantile"]) == 75.0) for m in V}
    frame = {vq[m]["main_frame"] for m in V}
    assert len(frame) == 1
    n_fr = 65
    body = (
        r"\caption{\textbf{One example per model at its lower budget}: \flux ($\delta="
        + f"{fm['delta']}$, {int(fq['nfe'])} " + r"\nfe), "
        + ", ".join(rf"{VNAME[m]} ($\delta={V[m]['delta']}$, {int(vq[m]['nfe'])} \nfe{VGATE[m]})" for m in V)
        + rf"; video: frame {frame.pop()} of {n_fr}. Fixed rule: among the prompts on which \seacache and \ours computed"
        r" identical steps, the one whose PSNR gain of \ours over \seacache is closest to the upper quartile."
        r" Numbers: per-image and per-video PSNR (dB) w.r.t.\ the 50-step reference. More in the supplement.}"
        + "\n" + r"\label{fig:qual-models}")
    write("fig_qual_models", body, r"\begin{figure}[t]\centering\includegraphics[width=\columnwidth]"
          r"{figures/fig_qual_models.pdf}\input{figures/fig_qual_models_caption}\end{figure}")


def video_examples(model):
    """supplementary material: two videos per model, five frames each (fig_video_examples.py)"""
    m = json.load(open(os.path.join(HERE, "qual_tiles", f"video_{model}", "meta.json")))
    gq = m["gain_quantiles"]
    nfe = {int(p["nfe"]) for p in m["prompts"]}
    assert len(nfe) == 1
    fr = m["frames"]
    body = (
        rf"\caption{{\textbf{{Video examples, {VNAME[model]}}} at {nfe.pop()} \nfe ($\delta={m['delta']}${VGATE[model]};"
        rf" VBench, 65 frames), frames {', '.join(map(str, fr[:-1]))} and {fr[-1]}. Fixed selection rule: among the"
        rf" {m['n_identical_steps']} of {m['n_total']} prompts on which \seacache and \ours computed the identical steps,"
        r" the videos whose per-video PSNR gain of \ours over \seacache is closest to the median"
        rf" ({sg(gq['50'])}\,dB; top) and to the upper quartile ({sg(gq['75'])}\,dB; bottom; also in"
        rf" \maincref{{fig:qual-models}}). Row labels: per-video PSNR (mean"
        r" over the 65 frames) with respect to the 50-step reference, best in bold.}" + "\n"
        + rf"\label{{fig:video-examples-{model}}}")
    write(f"fig_video_examples_{model}", body, rf"\begin{{figure*}}[t]\centering\includegraphics[width=\textwidth]"
          rf"{{figures/fig_video_examples_{model}.pdf}}\input{{figures/fig_video_examples_{model}_caption}}\end{{figure*}}")


def video_sweep():
    """Supplementary figure fig_video_sweep (fig_video_sweep.py): numbers from data/video_supp.json."""
    VS = json.load(open(os.path.join(HERE, "data", "video_supp.json")))
    A = VS["ablations"]["models"]
    sw = {m: sorted(A[m]["sweep"], key=lambda s: s["nfe_ours"]) for m in A}
    n = {m: A[m]["n_prompts"] for m in A}
    assert len(set(n.values())) == 1
    deltas = {m: ", ".join(f"{s['delta']:g}" for s in sorted(sw[m], key=lambda s: s["delta"])) for m in sw}
    g = lambda s: s["ours_minus_seacache"]["psnr"]
    # HunyuanVideo: every gain significant (checked); Wan2.1: sign / significance per budget, from the data
    assert all(g(s)["ci95"][0] > 0 for s in sw["hunyuan"]), "the caption assumes significant gains at every HV budget"
    hv_lo, hv_hi = sw["hunyuan"][0], sw["hunyuan"][-1]
    w = sorted(sw["wan"], key=lambda s: -s["nfe_ours"])
    pos = [s for s in w if g(s)["ci95"][0] > 0]
    ns = [s for s in w if g(s)["ci95"][0] <= 0 <= g(s)["ci95"][1]]
    neg = [s for s in w if g(s)["ci95"][1] < 0]
    assert pos and neg and len(pos) + len(ns) + len(neg) == len(w)
    lab = lambda x: f"{x:.0f}" if abs(x - round(x)) <= 0.06 else f"{x:.1f}"   # 20-prompt means such as 24.05 -> 24
    lst = lambda xs: " and ".join(lab(s["nfe_ours"]) for s in xs)
    same = {m: min(s["n_identical_schedules"] for s in sw[m]) for m in sw}
    body = (
        r"\caption{\textbf{Budget sweep on video} (" + str(n["hunyuan"]) + r" VBench prompts per model, those of"
        r" \cref{tab:supp-video-abl}; HunyuanVideo with the corrected gate). \textbf{(a, c)}~PSNR w.r.t.\ the 50-step"
        r" reference vs.\ \nfe for our same-setup re-run of \seacache and for \ours, which share the \sea gate and its"
        rf" threshold (HunyuanVideo $\delta\in\{{{deltas['hunyuan']}\}}$, Wan2.1 $\delta\in\{{{deltas['wan']}\}}$);"
        r" lines: means, shaded: 95\% bootstrap CIs. \textbf{(b, d)}~Paired PSNR gain of \ours over \seacache (mean,"
        r" 95\% CI); gray bands: the budgets of the main paper's \maincref{tab:video-main}. On HunyuanVideo, \ours is"
        rf" better at every budget ({ci(g(hv_lo))} at {lab(hv_lo['nfe_ours'])} \nfe, {ci(g(hv_hi))} at"
        rf" {lab(hv_hi['nfe_ours'])}). On Wan2.1 the gain shrinks with the budget: it is significant at {lst(pos)}"
        rf" \nfe, not significant at {lst(ns)} \nfe, and negative at "
        + " and ".join(f"{lab(s['nfe_ours'])} \\nfe ({ci(g(s))})" for s in neg)
        + r". Both methods computed the same steps on at least "
        + rf"{same['hunyuan']} (HunyuanVideo) and {same['wan']} (Wan2.1) of the {n['hunyuan']} prompts at every"
        r" threshold.}" "\n" r"\label{fig:video-sweep}")
    write("fig_video_sweep", body, r"\begin{figure}[t]\centering\includegraphics[width=\columnwidth]"
          r"{figures/fig_video_sweep.pdf}\input{figures/fig_video_sweep_caption}\end{figure}   (supplement)")


if __name__ == "__main__":
    import sys
    video_sweep()
    if sys.argv[1:] == ["--video"]:      # supplementary video figure only
        sys.exit(0)
    tradeoff()
    qualitative("nfe13", "fig_qualitative", "fig:qualitative", main=True)
    teaser("nfe13_teaser", "fig_qualitative_teaser", "fig:teaser")
    qualitative("nfe13_supp", "fig_qualitative_supp_nfe13", "fig:qualitative-supp-nfe13", main=False)
    qualitative("nfe21_supp", "fig_qualitative_supp_nfe21", "fig:qualitative-supp-nfe21", main=False)
    qual_models()
    video_examples("hunyuan")
    video_examples("wan")
