def tab_gains():
    import torch
    sig = torch.load(D.CALIB_TRAJ, map_location="cpu", weights_only=False)["sigmas"].double().numpy()[:50]
    cal = json.load(open(D.CALIB_JSON))
    p = np.asarray(cal["p_warp"], dtype=np.float64)
    q = np.asarray(cal["q"], dtype=np.float64)
    p22 = np.asarray(cal["p22_init"], dtype=np.float64)
    tau, R, Tw, Lb, N = 0.5, 1e-3, 2.0, 7, 50
    s_ = np.clip(sig, 1e-4, 1 - 1e-4)
    lam = 2.0 * np.log((1.0 - s_) / s_)
    s = np.zeros((Lb, N))
    for l in range(Lb):
        t = 1.0 / (1.0 + np.exp(-(lam + math.log(p[l])) / Tw))
        s[l] = 2.0 * (t - t[0]) / (t[-1] - t[0] + 1e-12) - 1.0
    dl = np.zeros_like(s)
    dl[:, 1:] = np.diff(s, axis=1)

    def AQ(j):
        A = np.zeros((Lb, 2, 2)); A[:, 0, 0] = 1; A[:, 0, 1] = dl[:, j]; A[:, 1, 1] = np.exp(-dl[:, j] / tau)
        Q = np.zeros((Lb, 2, 2)); Q[:, 0, 0] = dl[:, j] ** 3 / 3; Q[:, 0, 1] = Q[:, 1, 0] = dl[:, j] ** 2 / 2
        Q[:, 1, 1] = dl[:, j]
        return A, Q * q[:, None, None]
    sched = [0, 1, 2, 4, 6, 9, 13, 18, 25, 33, 41, 47, 49]
    P = np.stack([np.diag([R, p22[l]]) for l in range(Lb)])
    prior, gains, last = {}, {}, 0
    for j in range(1, N):
        A, Q = AQ(j)
        P = A @ P @ A.transpose(0, 2, 1) + Q
        if j in sched:
            S = P[:, 0, 0] + R
            Phi = np.tile(np.eye(2), (Lb, 1, 1))
            g = {}
            for i in range(j - 1, last, -1):
                Phi = Phi @ AQ(i + 1)[0]
                g[i] = (prior[i][:, 0, :] * Phi[:, 0, :]).sum(-1) / S
            gains[(last, j)] = g
            K = P[:, :, 0] / S[:, None]
            P = np.stack([(np.eye(2) - np.outer(K[l], [1.0, 0.0])) @ P[l] for l in range(Lb)])
            last = j
        else:
            prior[j] = P.copy()
    gap = (33, 41)
    L = [r"\begin{table}[t]", r"  \centering",
         r"  \caption{\textbf{RTS gains $g_{i,\ell}$ of the DCT forecaster} for the gap 33--41 of the most common 13-\nfe"
         r" schedule (0-based steps), per band $\ell$ (0: lowest frequencies), from the \flux calibration with the"
         r" process-noise scale fixed to $\kappa{=}1$ (no online adaptation, so the gains do not depend on the image). The"
         r" gains rise across the gap; early in the gap they are smaller for the high-frequency bands.}",
         r"  \label{tab:supp-gains}", r"  \footnotesize", r"  \setlength{\tabcolsep}{4pt}",
         r"  \begin{tabular}{@{}c ccccccc@{}}", r"    \toprule",
         r"    step $i$ & " + " & ".join(f"$\\ell{{=}}{l}$" for l in range(Lb)) + r" \\", r"    \midrule"]
    for i in sorted(gains[gap]):
        L.append(rf"    {i} & " + " & ".join(f"{v:.2f}" for v in gains[gap][i]) + r" \\")
    L += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    write("supp_gains", "\n".join(L))


