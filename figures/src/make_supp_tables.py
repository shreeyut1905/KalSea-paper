def sg(v, nd=2):
    s = f"{v:+.{nd}f}"
    if float(s) == 0.0 and v != 0.0:
        s = f"{v:+.{nd + 1}f}"
    return s.replace("-", "$-$")


def ci(p, nd=2):
    return f"{sg(p['mean'], nd)} {{\\scriptsize[{sg(p['ci95'][0], nd)}, {sg(p['ci95'][1], nd)}]}}"


def write(name, body):
    path = os.path.join(TAB, name + ".tex")
    open(path, "w").write(HEADER + body)
    print("wrote", path)


