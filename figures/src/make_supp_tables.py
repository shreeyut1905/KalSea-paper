def tab_correction():
    from collections import Counter, defaultdict
    rows, modal = [], None
    for d in sorted(ST["deltas"], key=lambda x: float(x)):
        recs = [json.loads(l) for f in glob.glob(os.path.join(D.RUN_DIR, D.PCGS_RUN.format(d=d), "stats_shard*.jsonl"))
                for l in open(f)]
        assert len(recs) == 200, (d, len(recs))
        allx, bylen = [], defaultdict(list)
        for r in recs:
            ps, st = r["plugin_stats"], r["compute_steps"]
            gaps = [(a, b) for a, b in zip(st[:-1], st[1:]) if b - a > 1]
            assert len(gaps) == len(ps["dx_rel"]) == len(ps["gap_len"])
            allx += ps["dx_rel"]
            for g, v in zip(ps["gap_len"], ps["dx_rel"]):
                bylen[g].append(v)
        out = np.mean([r["plugin_stats"]["n_out_calls"] for r in recs])
        gate = np.mean([r["plugin_stats"]["n_gate_recalc"] for r in recs])
        mx_len = max(bylen)
        rows.append((d, np.mean([r["nfe"] for r in recs]), 100 * np.mean(allx), 100 * np.mean(bylen[1]),
                     mx_len, 100 * np.mean(bylen[mx_len]), out, gate))
        if d == "0.6":
            cnt = Counter(tuple(r["compute_steps"]) for r in recs)
            sched, n = cnt.most_common(1)[0]
            per_gap = defaultdict(list)
            for r in recs:
                if tuple(r["compute_steps"]) != sched:
                    continue
                st = r["compute_steps"]
                gaps = [(a, b) for a, b in zip(st[:-1], st[1:]) if b - a > 1]
                for g, v in zip(gaps, r["plugin_stats"]["dx_rel"]):
                    per_gap[g].append(v)
            modal = (sched, n, {g: 100 * np.mean(v) for g, v in per_gap.items()})
    L = [r"\begin{table*}[t]", r"  \centering",
         r"  \caption{\textbf{Size of the latent correction} of \ours on \flux (DrawBench-200): relative correction"
         r" $\|\lat'_b-\lat_b\|/\|\lat_b\|$ at the computed step $b$ that closes a gap, averaged over all gaps, over the"
         r" gaps of length one, and over the gaps of the largest length; output-layer evaluations ($\Emb$ and $\Out$,"
         r" counted) and gate refreshes per image. Bottom: per gap of the most common schedule at $\delta{=}0.6$"
         r" (steps 0-based).}",
         r"  \label{tab:supp-correction}", r"  \footnotesize", r"  \setlength{\tabcolsep}{2.6pt}",
         r"  \begin{tabular}{@{}cc ccc cc@{}}", r"    \toprule",
         r"    & & \multicolumn{3}{c}{correction (\%)} & \multicolumn{2}{c}{per image} \\",
         r"    \cmidrule(lr){3-5} \cmidrule(l){6-7}",
         r"    $\delta$ & \nfe & all gaps & length 1 & longest & $\Emb$, $\Out$ & refresh \\", r"    \midrule"]
    for d, nfe, a, one, ml, lng, out, gate in rows:
        L.append(rf"    {d} & {nfe:.2f} & {a:.2f} & {one:.2f} & {lng:.2f} ({ml}) & {out:.1f} & {gate:.1f} \\")
    sched, n, pg = modal
    L += [r"    \midrule",
          rf"    \multicolumn{{7}}{{@{{}}l}}{{\emph{{$\delta{{=}}0.6$, schedule ({', '.join(map(str, sched))}),"
          rf" {n} prompts}}}} \\",
          r"    \multicolumn{7}{@{}l}{\begin{tabular}{@{}l" + "c" * len(pg) + r"@{}}"]
