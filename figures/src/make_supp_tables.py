def band_map(H=64, W=64):
    edges = [0.0, 1 / 64, 1 / 32, 1 / 16, 1 / 8, 1 / 4, 1 / 2, 1.0 + 1e-6]
    a = np.arange(H, dtype=np.float64)[:, None] / H
    b = np.arange(W, dtype=np.float64)[None, :] / W
    r = np.sqrt(a ** 2 + b ** 2) / math.sqrt(2.0)
    return np.searchsorted(np.array(edges[1:-1]), r, side="right"), edges


