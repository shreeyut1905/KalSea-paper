def numbers(per):
    """tables/supp_numbers.tex: \newcommand macros for statistics quoted in sections/supp.tex."""
    def boot(x):
        idx = np.random.default_rng(0).integers(0, len(x), size=(10000, len(x)))
        return np.percentile(x[idx].mean(1), [2.5, 97.5])
    L = ["% statistics quoted in sections/supp.tex (paired over prompts, bootstrap as in the harness)"]
    for d, tag in (("0.37", "A"), ("0.6", "B")):
        a, b = per[D.ABL[("dct", "off")].format(d=d)], per[D.MAIN["kalsea"].format(d=d)]
        fs = sorted(set(a) & set(b))
        x = np.array([a[f]["psnr"] - b[f]["psnr"] for f in fs])
        lo, hi = boot(x)
        same = sum(a[f]["compute_steps"] == b[f]["compute_steps"] for f in fs)
        L.append(rf"\newcommand{{\suppKalRerun{tag}}}{{{sg(x.mean())}\,dB [{sg(lo)}, {sg(hi)}]}}")
        L.append(rf"\newcommand{{\suppKalRerunSame{tag}}}{{{same}}}")
    for d, tag in (("0.37", "A"), ("0.6", "B")):
        o, k = per[D.MAIN["ours"].format(d=d)], per[D.MAIN["kalsea"].format(d=d)]
        fs = sorted(set(o) & set(k))
        g = np.array([o[f]["psnr"] - k[f]["psnr"] for f in fs])
        L.append(rf"\newcommand{{\suppPcgsMedian{tag}}}{{{np.median(g):.2f}}}")
        L.append(rf"\newcommand{{\suppPcgsNeg{tag}}}{{{int((g < 0).sum())}}}")
        L.append(rf"\newcommand{{\suppPcgsWorst{tag}}}{{{-g.min():.2f}}}")   # largest loss (positive number)
    write("supp_numbers", "\n".join(L) + "\n")


