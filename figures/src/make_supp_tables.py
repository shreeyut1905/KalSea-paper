def _parse_eval_txt(path):
    out = {}
    pat = re.compile(r"^(\S+)\s+(\d+)\s+([\d.]+)\s+[\d.]+\s+[\d.]+\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+[\d.]+\s+(\S+)\s+"
                     r"([+-][\d.]+)\s+\[([+-][\d.]+),([+-][\d.]+)\]\s+(\d+)")
    for line in open(path):
        m = pat.match(line)
        if m:
            g = m.groups()
            out[g[0]] = dict(n=int(g[1]), nfe=float(g[2]), psnr=float(g[3]), base=g[6], d=float(g[7]),
                             lo=float(g[8]), hi=float(g[9]), win=int(g[10]))
    return out


def _parse_halves(path):
    out = {}
    pat = re.compile(r"^(\S+)\s+(\S+)\s+(A|B|all)\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([+-][\d.]+)\s+"
                     r"\[([+-][\d.]+),([+-][\d.]+)\]\s+(\d+)")
    for line in open(path):
        m = pat.match(line)
        if m:
            g = m.groups()
            out[(g[0], g[1], g[2])] = dict(n=int(g[3]), nfe=float(g[4]), psnr=float(g[5]), bpsnr=float(g[6]),
                                           d=float(g[7]), lo=float(g[8]), hi=float(g[9]), win=int(g[10]))
    return out


