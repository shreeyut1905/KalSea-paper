    L.append(r"      corr.\ (\%) & " + " & ".join(f"{pg[g]:.2f}" for g in gaps) + r" \\")
    L += [r"    \end{tabular}} \\", r"    \bottomrule", r"  \end{tabular}", r"\end{table*}", ""]
