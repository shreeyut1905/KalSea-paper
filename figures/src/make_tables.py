def fmt(v, metric):
    return {"psnr": f"{v:.2f}", "ssim": f"{v:.3f}", "lpips": f"{v:.3f}", "nfe": f"{v:.2f}"}[metric]


def bold_best(rows, metric, lower_better=False):
    """rows: {name: value}; returns {name: formatted string with \\best{} on the best (ties at print precision)}."""
    shown = {k: fmt(v, metric) for k, v in rows.items()}
    vals = {k: float(s) for k, s in shown.items()}
    best = min(vals.values()) if lower_better else max(vals.values())
    return {k: (rf"\best{{{s}}}" if vals[k] == best else s) for k, s in shown.items()}


def signed(v, nd=2):
    return f"{v:+.{nd}f}".replace("-", "$-$") if v < 0 else f"{v:+.{nd}f}"


def ci(p, nd=2):
    lo, hi = p["ci95"]
    return f"{signed(p['mean'], nd)}\\,dB [{signed(lo, nd)}, {signed(hi, nd)}]"


