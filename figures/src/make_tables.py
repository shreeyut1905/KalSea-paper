# default keys (verified entries in tables/tables_refs.bib); a paper already in refs.bib is cited with refs.bib's key,
# found by title, so the tables follow whatever key the bibliography uses.
CITE = {"seacache": "chung2026seacache", "teacache": "liu2025teacache", "taylorseer": "liu2025taylorseer",
        "deltadit": "chen2024deltadit", "toca": "zou2025toca", "hunyuanvideo": "kong2024hunyuanvideo",
        "wan": "wan2025wan"}
TITLE = {"seacache": "spectral-evolution-aware cache", "teacache": "timestep embedding tells",
         "taylorseer": "from reusing to forecasting", "deltadit": "training-free acceleration method tailored for diffusion",
         "toca": "token-wise feature caching", "hunyuanvideo": "systematic framework for large video generative",
         "wan": "open and advanced large-scale video generative"}


def _bib_entries(path):
    import re
    if not os.path.exists(path):
        return {}
    txt = open(path).read()
    out = {}
    for m in re.finditer(r"@\w+\s*\{\s*([^,\s]+)\s*,(.*?)\n\}", txt, re.S):
        t = re.search(r"\btitle\s*=\s*[{\"](.*)", m.group(2), re.I)
        if t:
            out[m.group(1)] = re.sub(r"[{}\\$]", "", t.group(1)).lower()
    return out


def resolve_cite_keys():
    refs = _bib_entries(os.path.join(PAPER_DIR, "refs.bib"))
    ours = _bib_entries(os.path.join(TAB_DIR, "tables_refs.bib"))
    for pid, pat in TITLE.items():
        hit = [k for k, t in refs.items() if pat in t]
        if hit:
            CITE[pid] = hit[0]
            print(f"  cite {pid:12s} -> {hit[0]} (refs.bib)")
        elif CITE[pid] in ours:
            print(f"  cite {pid:12s} -> {CITE[pid]} (tables/tables_refs.bib: merge into refs.bib)")
        else:
            print(f"  cite {pid:12s} -> {CITE[pid]} (WARNING: not found in any .bib)")
HEADER = ("% Auto-generated by figures/src/make_tables.py from figures/src/data/flux_drawbench_stats.json"
          " -- edit the generator, not this file.\n")


def fmt(v, metric):
    return {"psnr": f"{v:.2f}", "ssim": f"{v:.3f}", "lpips": f"{v:.3f}", "nfe": f"{v:.2f}"}[metric]


def bold_best(rows, metric, lower_better=False):
    """rows: {name: value}; returns {name: formatted string with \\best{} on the best (ties at print precision)}."""
    shown = {k: fmt(v, metric) for k, v in rows.items()}
    vals = {k: float(s) for k, s in shown.items()}
    best = min(vals.values()) if lower_better else max(vals.values())
    return {k: (rf"\best{{{s}}}" if vals[k] == best else s) for k, s in shown.items()}


def signed(v, nd=2):
    return f"{v:+.{nd}f}".replace("-", "$-$") if v < 0 else f"{v:+.{nd}f}"


def ci(p, nd=2):
    lo, hi = p["ci95"]
    return f"{signed(p['mean'], nd)}\\,dB [{signed(lo, nd)}, {signed(hi, nd)}]"


