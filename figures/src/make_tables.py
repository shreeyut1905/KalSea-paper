def _bib_entries(path):
    import re
    if not os.path.exists(path):
        return {}
    txt = open(path).read()
    out = {}
    for m in re.finditer(r"@\w+\s*\{\s*([^,\s]+)\s*,(.*?)\n\}", txt, re.S):
        t = re.search(r"\btitle\s*=\s*[{\"](.*)", m.group(2), re.I)
        if t:
            out[m.group(1)] = re.sub(r"[{}\\$]", "", t.group(1)).lower()
    return out


