# ---------------------------------------------------------------- Table: 2x2 ablation {DCT, per-element} x {PCGS off, on}
def tab_ablation_2x2():
    A = ST["ablation_2x2"]
    budgets = [("0.37", "18.1"), ("0.6", "13")]
    # check matched NFE
    for d, _ in budgets:
        n = [A[d]["summary"][k]["nfe"] for k in ("dct_off", "dct_on", "elem_off", "elem_on")]
        assert max(n) - min(n) < 0.05, (d, n)
    keys = ("dct_off", "dct_on", "elem_off", "elem_on")
    cols = {}
    for d, _ in budgets:
        for m in ("psnr", "ssim", "lpips"):
            cols[(d, m)] = bold_best({k: A[d]["summary"][k][m]["mean"] for k in keys}, m, lower_better=(m == "lpips"))
    nfe_txt = {d: "/".join(sorted({f"{A[d]['summary'][k]['nfe']:.2f}" for k in keys})) for d, _ in budgets}

    def row(k, label, mark):
        cells = " & ".join(cols[(d, m)][k] for d, _ in budgets for m in ("psnr", "ssim", "lpips"))
        return rf"    {label} & {mark} & {cells} \\"

    def drow(pair):
        parts = []
        for d, _ in budgets:
            p = A[d][pair]["psnr"]
            parts.append(rf"\multicolumn{{3}}{{c}}{{\scriptsize {ci(p)}}}")
        return r"     & $\Delta$ & " + " & ".join(parts) + r" \\"

    x = {d: A[d]["dct_on-elem_on"]["psnr"] for d, _ in budgets}
    L = [HEADER,
         "% DCT/off = KalSea (DCT bands) run in the same harness as DCT/on; per-element/off = KalSea per-element.",
         f"% Mean NFE per budget (all four cells): {nfe_txt['0.37']} at delta=0.37 and {nfe_txt['0.6']} at delta=0.6.",
         r"\begin{table}[t]",
         r"  \centering",
         r"  \caption{\textbf{Gap smoothing helps both forecaster variants.} \flux on DrawBench-200 at matched \nfe;"
         r" rows: Kalman forecaster on DCT bands (with band-specific warped time) or per element, without (\xmark) or with"
         r" (\cmark) predictor-corrector gap smoothing (\pcgs). $\Delta$: paired PSNR gain of \pcgs with 95\% bootstrap CI"
         r" over prompts. With \pcgs, the two forecasters do not differ significantly (DCT minus per-element: "
         + ci(x["0.37"]) + r" at 18.1 \nfe, " + ci(x["0.6"]) + r" at 13 \nfe). Best per column in bold.}",
         r"  \label{tab:ablation-2x2}",
         r"  \footnotesize",
         r"  \setlength{\tabcolsep}{2.4pt}",
         r"  \begin{tabular}{@{}llcccccc@{}}",
         r"    \toprule",
         r"    & & \multicolumn{3}{c}{18.1 \nfe ($\delta{=}0.37$)} & \multicolumn{3}{c}{13 \nfe ($\delta{=}0.6$)} \\",
         r"    \cmidrule(lr){3-5} \cmidrule(l){6-8}",
         r"    Forecaster & \pcgs & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ \\",
         r"    \midrule",
         row("dct_off", "DCT bands", r"\xmark"),
         row("dct_on", "", r"\cmark"),
         drow("dct_on-dct_off"),
         r"    \midrule",
         row("elem_off", "Per element", r"\xmark"),
         row("elem_on", "", r"\cmark"),
         drow("elem_on-elem_off"),
         r"    \bottomrule",
         r"  \end{tabular}",
         r"\end{table}",
         ""]
    return "\n".join(L)


# ---------------------------------------------------------------- Table (supplement): full budget sweep = table view of fig_tradeoff
def tab_flux_sweep():
    S, P = ST["summary"], ST["paired"]
    ds = sorted(ST["deltas"], key=lambda d: -S[d]["ours"]["nfe"])
    dmax = max(max(S[d][m]["nfe"] for m in ("seacache", "kalsea", "ours")) - min(S[d][m]["nfe"] for m in ("seacache", "kalsea", "ours")) for d in ds)
    L = [HEADER,
         "% Table view of figures/fig_tradeoff.pdf (all seven budgets). Intended for the supplementary material.",
         r"\begin{table*}[t]",
         r"  \centering",
         r"  \caption{\textbf{All budgets of \cref{fig:tradeoff}} (\flux, DrawBench-200, metrics w.r.t.\ the 50-step reference)."
         r" The \sea-gate threshold $\delta$ sets the budget and is shared by the three methods; \nfe is the mean of \ours (the"
         rf" three methods differ by at most {math.ceil(dmax * 100 - 1e-9) / 100:.2f} \nfe at any $\delta$). $\Delta$PSNR: paired per-prompt gain of \ours with"
         r" 95\% bootstrap CI over prompts. Best per row and metric in bold.}",
         r"  \label{tab:flux-sweep}",
         r"  \footnotesize",
         r"  \setlength{\tabcolsep}{3pt}",
         r"  \begin{tabular}{@{}cc ccc ccc ccc cc@{}}",
         r"    \toprule",
         r"    & & \multicolumn{3}{c}{\seacache} & \multicolumn{3}{c}{\kalsea (no smoothing)} & \multicolumn{3}{c}{\ours}"
         r" & \multicolumn{2}{c}{$\Delta$PSNR of \ours (dB)} \\",
         r"    \cmidrule(lr){3-5} \cmidrule(lr){6-8} \cmidrule(lr){9-11} \cmidrule(l){12-13}",
         r"    $\delta$ & \nfe & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$"
         r" & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ & vs.\ \seacache & vs.\ \kalsea \\",
         r"    \midrule"]
    for d in ds:
        cols = {m: bold_best({k: S[d][k][m]["mean"] for k in ("seacache", "kalsea", "ours")}, m, lower_better=(m == "lpips"))
                for m in ("psnr", "ssim", "lpips")}
        cells = " & ".join(cols[m][k] for k in ("seacache", "kalsea", "ours") for m in ("psnr", "ssim", "lpips"))
        g = [P[d][x]["psnr"] for x in ("ours-seacache", "ours-kalsea")]
        gtxt = " & ".join(rf"{signed(p['mean'])} [{signed(p['ci95'][0], 2 if abs(p['ci95'][0]) >= 0.005 else 3)}, {signed(p['ci95'][1])}]" for p in g)
        L.append(rf"    {d} & {S[d]['ours']['nfe']:.2f} & {cells} & {gtxt} \\")
    L += [r"    \bottomrule", r"  \end{tabular}", r"\end{table*}", ""]
    return "\n".join(L)


def main():
    os.makedirs(TAB_DIR, exist_ok=True)
    resolve_cite_keys()
    for name, fn in (("tab_flux_main", tab_flux_main), ("tab_video_main", tab_video_main),
                     ("tab_ablation_2x2", tab_ablation_2x2), ("tab_flux_sweep", tab_flux_sweep)):
        path = os.path.join(TAB_DIR, name + ".tex")
        open(path, "w").write(fn())
        print("wrote", path)


if __name__ == "__main__":
    main()
