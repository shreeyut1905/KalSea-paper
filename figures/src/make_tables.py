def tab_ablation_2x2():
    A = ST["ablation_2x2"]
    budgets = [("0.37", "18.1"), ("0.6", "13")]
    # check matched NFE
    for d, _ in budgets:
        n = [A[d]["summary"][k]["nfe"] for k in ("dct_off", "dct_on", "elem_off", "elem_on")]
        assert max(n) - min(n) < 0.05, (d, n)
    keys = ("dct_off", "dct_on", "elem_off", "elem_on")
    cols = {}
    for d, _ in budgets:
        for m in ("psnr", "ssim", "lpips"):
            cols[(d, m)] = bold_best({k: A[d]["summary"][k][m]["mean"] for k in keys}, m, lower_better=(m == "lpips"))
    nfe_txt = {d: "/".join(sorted({f"{A[d]['summary'][k]['nfe']:.2f}" for k in keys})) for d, _ in budgets}

    def row(k, label, mark):
        cells = " & ".join(cols[(d, m)][k] for d, _ in budgets for m in ("psnr", "ssim", "lpips"))
        return rf"    {label} & {mark} & {cells} \\"

    def drow(pair):
        parts = []
